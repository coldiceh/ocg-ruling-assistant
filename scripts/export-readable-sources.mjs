import { createHash } from 'node:crypto';
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderReadableData, READABLE_EVIDENCE_FORMAT } from '../backend/readableEvidenceText.mjs';

export const READABLE_SOURCE_FILES = Object.freeze([
  'cards.json', 'rulings.json', 'qa-index.json', 'ocg-rule-corpus.json', 'official-responses.json',
]);

// Derived reading copies only. Original JSON, hashes, ranges, indexes and paid
// navigation/vector results are neither edited nor regenerated by this export.
export async function exportReadableSources({
  dataDir = fileURLToPath(new URL('../data', import.meta.url)),
  outDir = join(dataDir, 'readable-sources'),
  names = READABLE_SOURCE_FILES,
} = {}) {
  await mkdir(outDir, { recursive: true });
  const files = [], missing = [];
  for (const name of names) {
    let bytes;
    try { bytes = await readFile(join(dataDir, name)); }
    catch (error) { if (error.code === 'ENOENT') { missing.push(name); continue; } throw error; }
    const data = JSON.parse(bytes.toString('utf8').replace(/^\uFEFF/u, ''));
    const records = Array.isArray(data) ? data : data.records;
    // These envelopes have an explicit records field. Sync diagnostics and
    // storage versions remain in JSON; record fields and their order survive.
    const displayed = Array.isArray(records) ? {
      ...(data.source ? { source: data.source } : {}),
      ...(data.generatedAt ? { generatedAt: data.generatedAt } : {}),
      records: records.map(record => {
        // The rule scraper's structure field contains offsets, DOM block keys
        // and hashes. Its canonical text already carries headings and cells.
        if (record.recordType !== 'rule-doc') return record;
        const { structure: _lookupMetadata, ...readingFields } = record;
        return readingFields;
      }),
    } : data;
    const text = renderReadableData(displayed) + '\n';
    const output = basename(name, '.json') + '.txt';
    const temporary = join(outDir, output + '.tmp');
    await writeFile(temporary, text, 'utf8');
    await rename(temporary, join(outDir, output));
    files.push({ source: name, output, records: Array.isArray(records) ? records.length : null,
      sourceSha256: createHash('sha256').update(bytes).digest('hex'),
      outputSha256: createHash('sha256').update(text).digest('hex'),
      outputChars: text.length, outputBytes: Buffer.byteLength(text) });
  }
  return { format: READABLE_EVIDENCE_FORMAT, files, missing };
}

if (resolve(process.argv[1] || '') === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2), options = {};
  for (let i = 0; i < args.length; i += 2) {
    const key = { '--data-dir': 'dataDir', '--out-dir': 'outDir' }[args[i]];
    if (!key || !args[i + 1]) throw new Error('export-readable-sources: invalid argument');
    options[key] = resolve(args[i + 1]);
  }
  console.log(JSON.stringify(await exportReadableSources(options), null, 2));
}
